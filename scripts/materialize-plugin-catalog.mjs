// Materialize the release's static facts from its real plugin manifests.
// Worker imports only the generated data, never the Window implementation graph.
import { readFile, writeFile } from "node:fs/promises";
import { createServer } from "vite";
import { resolve } from "node:path";
const root = process.cwd();
const check = !process.argv.includes("--write");
const descriptor = ({ kind, id, version }) => ({ kind, id, version });
const server = await createServer({ root, configFile: false, server: { middlewareMode: true }, ssr: { noExternal: [/^@keymaster\//] } });
try {
  const { WEB_PLUGIN_CATALOG_SOURCE: WEB_PLUGIN_CATALOG } = await server.ssrLoadModule("/apps/web/src/pluginCatalogSource.ts");
  const facts = WEB_PLUGIN_CATALOG.map(plugin => ({ id: plugin.id, name: plugin.name,
    units: plugin.units.map(unit => ({ id: unit.id, runtime: unit.runtime, scopeKind: unit.scopeKind,
      provides: (unit.provides ?? []).map(descriptor), privateProvides: (unit.privateProvides ?? []).map(descriptor), dependencies: (unit.dependencies ?? []).map(dependency => ({ ...dependency, capability: descriptor(dependency.capability) })),
      connect: unit.connect, permissions: unit.permissions ?? [], storages: unit.storages ?? (unit.storage ? [unit.storage] : []),
    })),
  }));
  const generatedPath = resolve(root, "packages/contracts/src/generated/pluginDefinitions.ts");
  const generated = "// Generated by scripts/materialize-plugin-catalog.mjs --write; do not edit.\nexport const BUILTIN_PLUGIN_DEFINITIONS = " + JSON.stringify(facts, null, 2) + " as const;\n";
  const productPath = resolve(root, "packages/contracts/src/pluginProducts.ts");
  const existing = await readFile(productPath, "utf8");
  const ids = "export const BUILTIN_PLUGIN_PRODUCT_IDS = [\n" + facts.map(plugin => `  ${JSON.stringify(plugin.id)},`).join("\n") + "\n] as const";
  const units = "export const BUILTIN_PLUGIN_RUNTIME_UNIT_CATALOG = [\n" + facts.flatMap(plugin => plugin.units.map(unit => `  { productId: ${JSON.stringify(plugin.id)}, unitId: ${JSON.stringify(unit.id)}, runtime: ${JSON.stringify(unit.runtime)}, scopeKind: ${JSON.stringify(unit.scopeKind)} },`)).join("\n") + "\n] as const satisfies readonly BuiltinPluginRuntimeUnitDeclaration[]";
  const product = existing.replace(/export const BUILTIN_PLUGIN_PRODUCT_IDS = \[[\s\S]*?\] as const/u, ids).replace(/export const BUILTIN_PLUGIN_RUNTIME_UNIT_CATALOG = \[[\s\S]*?\] as const satisfies readonly BuiltinPluginRuntimeUnitDeclaration\[\]/u, units);
  if (product === existing && !existing.includes(ids)) throw new Error("Product catalog materialization target missing");
  for (const [path, expected] of [[generatedPath, generated], [productPath, product]]) {
    if (check) {
      const actual = await readFile(path, "utf8").catch(() => "");
      if (actual !== expected) throw new Error(`${path} is stale; run pnpm generate:plugin-catalog`);
    } else await writeFile(path, expected);
  }
  console.log(`Plugin catalog ${check ? "verified" : "materialized"}: ${facts.length} products, ${facts.reduce((sum, plugin) => sum + plugin.units.length, 0)} units.`);
} finally { await server.close(); }
